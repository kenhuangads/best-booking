export const CITY_MAP = new Map(CITIES.map((c) => [c.key, c]));

export function getCity(key: string): City | undefined {
  return CITY_MAP.get(key.toUpperCase());
}

export function cityName(key: string): string {
  return getCity(key)?.name ?? key;
}

export function searchCities(q: string): City[] {
  const s = q.trim().toLowerCase();
  if (!s) return [];
  const score = (c: City): number => {
    if (c.key.toLowerCase() === s) return 100;
    if (c.name.toLowerCase() === s) return 95;
    if (c.name.toLowerCase().startsWith(s)) return 80;
    if (c.name.toLowerCase().includes(s)) return 60;
    if (c.aliases?.some((x) => x.toLowerCase().includes(s))) return 50;
    if (c.areas.some((x) => x.toLowerCase().includes(s))) return 40;
    if (c.country.toLowerCase().includes(s)) return 30;
    return 0;
  };
  return CITIES.map((c) => ({ c, s: score(c) }))
    .filter((x) => x.s > 0)
    .sort((x, y) => y.s - x.s)
    .map((x) => x.c);
}

