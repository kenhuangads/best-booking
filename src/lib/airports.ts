export const AIRPORT_MAP = new Map(AIRPORTS.map((a) => [a.code, a]));

export function getAirport(code: string): Airport | undefined {
  return AIRPORT_MAP.get(code.toUpperCase());
}

/** 台北 TPE */
export function airportLabel(code: string): string {
  const a = getAirport(code);
  return a ? `${a.city} ${a.code}` : code;
}

export function airportCity(code: string): string {
  return getAirport(code)?.city ?? code;
}

export function isTaiwan(code: string): boolean {
  return getAirport(code)?.region === '台灣';
}

export function searchAirports(q: string): Airport[] {
  const s = q.trim().toLowerCase();
  if (!s) return [];
  const score = (a: Airport): number => {
    if (a.code.toLowerCase() === s) return 100;
    if (a.city.toLowerCase() === s) return 90;
    if (a.city.toLowerCase().startsWith(s)) return 80;
    if (a.code.toLowerCase().startsWith(s)) return 75;
    if (a.city.toLowerCase().includes(s) || a.name.toLowerCase().includes(s)) return 60;
    if (a.aliases?.some((x) => x.toLowerCase().includes(s))) return 50;
    if (a.country.toLowerCase().includes(s)) return 30;
    return 0;
  };
  return AIRPORTS.map((a) => ({ a, s: score(a) }))
    .filter((x) => x.s > 0)
    .sort((x, y) => y.s - x.s)
    .map((x) => x.a);
}

